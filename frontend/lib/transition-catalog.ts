/** All unique family names, in display order */
export const FAMILIES = [...new Set(TRANSITION_CATALOG.map((t) => t.family))];

/** Map of family name → entries */
export function getTransitionsByFamily(): Record<string, TransitionCatalogEntry[]> {
  const result: Record<string, TransitionCatalogEntry[]> = {};
  for (const entry of TRANSITION_CATALOG) {
    if (!result[entry.family]) result[entry.family] = [];
    result[entry.family].push(entry);
  }
  return result;
}

/** Top 5 featured transitions for sidebar and marketing */
export const FEATURED_TRANSITIONS = TRANSITION_CATALOG.filter((t) => t.featured).slice(0, 5);

/** Lookup a single transition by slug */
export function getCatalogEntry(slug: string): TransitionCatalogEntry | undefined {
  return TRANSITION_CATALOG.find((t) => t.slug === slug);
}

/** All slugs for static param generation */
export function getAllTransitionSlugs(): string[] {
  return TRANSITION_CATALOG.map((t) => t.slug);
}

