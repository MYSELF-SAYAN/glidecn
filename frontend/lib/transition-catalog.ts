/* ==========================================================================
 * GlideCN — Transition Catalog
 * The single source of truth for ALL transition metadata used across the
 * documentation site: sidebar, gallery, showcase pages, and overview cards.
 *
 * To add a new transition to the docs, add an entry here. Everything else
 * (sidebar, gallery, doc pages) auto-syncs from this file.
 * ========================================================================== */

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface TransitionMetrics {
  /** Target FPS (always 60 for GPU-accelerated) */
  fps: number;
  /** Approximate gzipped bundle contribution in KB */
  bundleSize: string;
  /** Complexity: 'Low' | 'Medium' | 'High' */
  complexity: 'Low' | 'Medium' | 'High';
}

export interface TransitionCatalogEntry {
  /** Machine-readable slug (must match the registry name) */
  slug: string;
  /** Human-friendly display name */
  displayName: string;
  /** One-liner tagline */
  description: string;
  /** Extended description for the showcase page */
  longDescription: string;
  /** Grouping category (matches TransitionCategory type) */
  category: 'flow' | 'portal' | 'paper' | 'mask' | 'spatial' | 'dynamic' | 'experimental';
  /** Family group name for sidebar/gallery */
  family: string;
  /** Playful emoji icon */
  emoji: string;
  /** Whether this appears in the "Featured" sidebar section */
  featured: boolean;
  /** Performance & size metrics */
  metrics: TransitionMetrics;
  /** Ideal use-case descriptions */
  useCases: string[];
  /** What makes this transition special — shown as a highlight */
  whySpecial: string;
  /** Short tags for "Best for" pills */
  bestFor: string[];
  /** Feature flags — what the transition provides */
  features: string[];
  /** Implementation status */
  status?: 'done' | 'coming-soon';
}

