console.log('─'.repeat(50));
console.log('');

// Step 1: Copy templates
console.log('📦 Copying frontend/components/morphy → cli/templates/');
copyRecursive(FRONTEND_MORPHY, TEMPLATES_DIR);
console.log('   ✅ Templates synced');
console.log('');

// Step 2: Extract metadata
console.log('🔍 Scanning transition metadata...');
const metas = scanTransitions();
console.log(`   Found ${metas.length} transitions`);
console.log('');

// Step 3: Generate catalog
console.log('📝 Generating src/data/transitions.ts...');
const catalog = generateCatalog(metas);
const dataDir = path.dirname(DATA_OUTPUT);
if (!fs.existsSync(dataDir)) {
  fs.mkdirSync(dataDir, { recursive: true });
}
fs.writeFileSync(DATA_OUTPUT, catalog, 'utf-8');
console.log('   ✅ Catalog generated');
console.log('');

